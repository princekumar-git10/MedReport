// Helper: Read referrals from local storage
export function getLocalReferrals() {
  try {
    if (typeof localStorage === "undefined") return DEMO_REFERRALS;
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(DEMO_REFERRALS));
      return DEMO_REFERRALS;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed)) {
      // Ensure any demo referral not yet present is merged cleanly
      let merged = [...parsed];
      let added = false;
      for (const demo of DEMO_REFERRALS) {
        if (!merged.some(r => r.id === demo.id)) {
          merged.push(demo);
          added = true;
        }
      }
      if (added) {
        localStorage.setItem(STORAGE_KEY, JSON.stringify(merged));
      }
      return merged;
    }
    return DEMO_REFERRALS;
  } catch (e) {
    console.error("Local referrals read error:", e);
    return DEMO_REFERRALS;
  }
}

// Helper: Save referrals locally
export function saveLocalReferrals(list) {
  try {
    if (typeof localStorage !== "undefined") {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(list));
    }
    if (typeof window !== "undefined") {
      window.dispatchEvent(new CustomEvent("relief_referrals_updated", { detail: list }));
    }
  } catch (e) {
    console.error("Local referrals write error:", e);
  }
}

/**
 * Fetch all referrals (optionally filtered by doctor ID)
 */
export async function getReferrals(doctorId = null) {
  let list = getLocalReferrals();

  if (db && typeof window !== "undefined" && window.navigator?.onLine !== false) {
    try {
      const snap = await withTimeout(getDocs(collection(db, FIRESTORE_COLLECTION)), 2000);
      if (!snap.empty) {
        const cloudList = [];
        snap.forEach(d => cloudList.push({ id: d.id, ...d.data() }));
        saveLocalReferrals(cloudList);
        list = cloudList;
      }
    } catch (e) {
      console.warn("Firestore referrals sync skipped, using local store:", e.message);
    }
  }

  if (doctorId) {
    const normDocId = doctorId.toLowerCase();
    // Strict authorization: doctor only sees their own live referrals (+ shared demo samples)
    return list.filter(
      (r) => r.doctorId?.toLowerCase() === normDocId || r.isDemoData === true
    );
  }

  return list;
}

/**
 * Fetch single referral by ID
 */
export async function getReferralById(id) {
  const all = await getReferrals();
  return all.find(r => r.id === id) || null;
}

/**
 * Validate and create a structured Doctor Referral.
 * Enforces mandatory fields:
 * - Patient Name, Age, Contact, Location
 * - Required Specialty, Treatment/Procedure, Diagnosis
 * - Doctor ID & Name
 */
export async function createReferral(formData, doctorInfo = {}) {
  // 1. Mandatory Validations
  if (!formData.patientName?.trim()) {
    throw new Error("Patient name is required.");
  }
  const age = parseInt(formData.patientAge, 10);
  if (isNaN(age) || age <= 0 || age > 130) {
    throw new Error("Valid patient age is required.");
  }
  if (!formData.patientContact?.trim()) {
    throw new Error("Patient contact number is required.");
  }
  if (!formData.patientLocation?.trim()) {
    throw new Error("Patient location / city is required.");
  }
  if (!formData.specialty?.trim()) {
    throw new Error("Required medical specialty is required.");
  }
  if (!formData.procedure?.trim()) {
    throw new Error("Required treatment or procedure is required.");
  }
  if (!formData.diagnosis?.trim()) {
    throw new Error("Diagnosis or clinical notes are required.");
  }

  // 1b. Duplicate referral guard (prevent accidental double submission for same active patient+procedure)
  const existingList = getLocalReferrals();
  if (!formData.allowDuplicate) {
    const normName = formData.patientName.trim().toLowerCase();
    const normContact = formData.patientContact.replace(/\s+/g, "").toLowerCase();
    const normProc = formData.procedure.trim().toLowerCase();
    const activeStatuses = ["Created", "Pending", "Information Requested", "Accepted", "Transfer Initiated", "Patient Arrived"];

    const duplicate = existingList.find((r) => {
      const rName = (r.patient?.name || "").trim().toLowerCase();
      const rContact = (r.patient?.contact || "").replace(/\s+/g, "").toLowerCase();
      const rProc = (r.clinicalRequirements?.procedure || "").trim().toLowerCase();
      return activeStatuses.includes(r.status) && rName === normName && rContact === normContact && rProc === normProc;
    });

    if (duplicate) {
      throw new Error(
        `Duplicate referral blocked: Active referral ${duplicate.id} already exists for ${formData.patientName} (${formData.procedure}) with status "${duplicate.status}".`
      );
    }
  }

  // 2. Generate Unique Referral ID
  const year = new Date().getFullYear();
  const randomCode = Math.floor(1000 + Math.random() * 9000);
  const referralId = `REF-RLH-${year}-${randomCode}`;

  const patientId = formData.patientId?.trim() || `PID-${year}-${Math.floor(1000 + Math.random() * 9000)}`;
  const doctorEmail = (doctorInfo.email || formData.doctorEmail || "dr.physician@clinic.med").toLowerCase();
  const doctorName = doctorInfo.name || formData.doctorName || "Dr. Referring Clinician";
  const doctorClinic = doctorInfo.clinic || formData.doctorClinic || "Referring Clinic Desk";

  const nowIso = new Date().toISOString();

  // 3. Structured Referral Object
  const newReferral = {
    id: referralId,
    isDemoData: false,
    sourceNote: "Accredited Clinical Referral",
    status: "Created",
    createdAt: nowIso,
    doctorId: doctorEmail,
    doctorName,
    doctorClinic,
    priority: formData.priority || "Urgent", // "Emergency" | "Urgent" | "Routine"
    patient: {
      name: formData.patientName.trim(),
      patientId,
      age,
      gender: formData.gender || "Clinically Non-specified",
      contact: formData.patientContact.trim(),
      location: formData.patientLocation.trim(),
      emergencyContact: formData.emergencyContact?.trim() || "Not provided",
    },
    // Mandatory clinical requirements stored separately
    clinicalRequirements: {
      specialty: formData.specialty.trim(),
      procedure: formData.procedure.trim(),
      diagnosis: formData.diagnosis.trim(),
      hospitalFacilities: formData.hospitalFacilities?.trim() || "Standard Surgical & Recovery Facilities",
      icuRequired: Boolean(formData.icuRequired),
      emergencySupportRequired: Boolean(formData.emergencySupportRequired),
      requiredSpecialist: formData.requiredSpecialist?.trim() || "Attending Specialist",
      equipmentRequirements: formData.equipmentRequirements?.trim() || "Standard Surgical Lasers & OR Suite",
      additionalClinicalNotes: formData.additionalClinicalNotes?.trim() || "None reported.",
    },
    preferences: {
      preferredLocation: formData.preferredLocation?.trim() || formData.patientLocation.trim(),
      maxDistance: formData.maxDistance || "50 km",
      insuranceRequirements: formData.insuranceRequirements?.trim() || "Self-Pay / Cashless TPA",
    },
    documents: Array.isArray(formData.documents) ? formData.documents : [],
    targetHospitalId: null,
    targetHospitalName: null,
    timeline: [
      {
        status: "Created",
        timestamp: nowIso,
        note: `Structured referral generated by ${doctorName} (${doctorClinic}). Ready for hospital matching.`,
        by: doctorName,
      },
    ],
    notifications: [
      {
        notifiedAt: nowIso,
        target: "patient",
        title: "Referral Created",
        message: `Your referral (${referralId}) has been created by ${doctorName}. Hospital matching is underway.`,
      },
    ],
  };

  // 4. Save to local database
  const updated = [newReferral, ...existingList];
  saveLocalReferrals(updated);

  // 5. Evaluate eligible hospitals and notify them + patient in real time
  try {
    const allHospitals = await getHospitals();
    const matchRun = runMatchingEngine(newReferral, allHospitals);
    const eligibleList = matchRun.eligibleHospitals || [];

    for (const item of eligibleList.slice(0, 5)) {
      await dispatchNotification({
        recipientRole: "hospital",
        recipientId: item.hospital.id,
        referralId,
        eventType: "eligible_referral_available",
        title: "New Eligible Referral Matched",
        message: `${newReferral.priority} case (${newReferral.clinicalRequirements.specialty} - ${newReferral.clinicalRequirements.procedure}) matches ${item.hospital.name} (${item.matchScore}% score).`,
        requestedExternalChannels: ["email"],
        isDemoData: false,
      });
    }

    await dispatchNotification({
      recipientRole: "patient",
      recipientId: patientId,
      referralId,
      eventType: "referral_created",
      title: "Hospital Referral Created",
      message: `Your referral ${referralId} has been registered by ${doctorName}. Matching accredited hospitals in progress.`,
      requestedExternalChannels: ["sms", "email", "whatsapp"],
      isDemoData: false,
    });
  } catch (notifyErr) {
    console.warn("Eligible hospital notification dispatch skipped:", notifyErr.message);
  }

  // 6. Sync to Firestore in background
  if (db && typeof window !== "undefined" && window.navigator?.onLine !== false) {
    withTimeout(setDoc(doc(db, FIRESTORE_COLLECTION, referralId), newReferral), 2500)
      .catch((e) => console.warn("Firestore referral save skipped:", e.message));
  }

  return newReferral;
}

/**
 * Match hospitals against a referral using the deterministic matchingEngine.js source of truth.
 */
export async function matchHospitalsForReferral(referral) {
  const allHospitals = await getHospitals();
  const engineResult = runMatchingEngine(referral, allHospitals);

  const formatCard = (item) => ({
    hospital: item.hospital,
    matchScore: item.matchScore,
    matchGrade: item.isEligible
      ? item.matchScore >= 80
        ? "Optimal Match"
        : "Compatible Match"
      : "Ineligible (Clinical Filter)",
    matchReasons: item.passedCriteria || [],
    missingRequirements: item.missingCriteria || [],
    bedsOpen: item.hospital.availableBeds,
    icuOpen: item.hospital.icuFacilities?.availableBeds ?? item.hospital.icuBedCapacity ?? 0,
    emergencyOpen: item.hospital.availableEmergencyBeds,
    confirmed: item.hospital.confirmedByHospital,
    distanceKm: item.distanceKm,
    travelTime: item.travelTime,
    explanation: item.explanation,
    isEligible: item.isEligible,
  });

  // Eligible hospitals first, followed by ineligible with explicit missing requirements
  const eligibleCards = (engineResult.eligibleHospitals || []).map(formatCard);
  const ineligibleCards = (engineResult.unsuitableHospitals || []).map(formatCard);
  return [...eligibleCards, ...ineligibleCards];
}

/**
 * Dispatch a referral to a selected hospital
 */
export async function dispatchReferralToHospital(referralId, hospitalId, hospitalName, doctorName = "Referring Clinician") {
  const list = getLocalReferrals();
  const index = list.findIndex((r) => r.id === referralId);
  if (index === -1) throw new Error("Referral not found");

  const current = list[index];

  // Duplicate dispatch check
  if (current.targetHospitalId === hospitalId && ["Pending", "Accepted"].includes(current.status)) {
    throw new Error(`Duplicate dispatch blocked: Referral ${referralId} is already ${current.status} at ${hospitalName}.`);
  }

  // Status transition guard (allow initial Created->Pending or re-dispatch from Pending/Rejected)
  if (current.status !== "Pending") {
    validateStatusTransition(current.status, "Pending");
  }

  const nowIso = new Date().toISOString();

  const updated = {
    ...current,
    status: "Pending",
    targetHospitalId: hospitalId,
    targetHospitalName: hospitalName,
    dispatchedAt: nowIso,
    timeline: [
      ...current.timeline,
      {
        status: "Pending",
        timestamp: nowIso,
        note: `Dispatched to ${hospitalName} admissions desk. Digital referral token issued.`,
        by: doctorName,
      },
    ],
    notifications: [
      ...(current.notifications || []),
      {
        notifiedAt: nowIso,
        target: "patient_and_hospital",
        title: "Referral Dispatched to Hospital",
        message: `Referral ${referralId} has been dispatched to ${hospitalName} admissions triage desk.`,
      },
    ],
  };

  list[index] = updated;
  saveLocalReferrals(list);

  await dispatchNotification({
    recipientRole: "hospital",
    recipientId: hospitalId,
    referralId,
    eventType: "referral_dispatched",
    title: "Incoming Referral Request",
    message: `New ${updated.priority} referral (${referralId}) received from ${doctorName} for ${updated.clinicalRequirements?.procedure}.`,
    requestedExternalChannels: ["email"],
    isDemoData: updated.isDemoData,
  });

  await dispatchNotification({
    recipientRole: "patient",
    recipientId: updated.patient?.patientId || referralId,
    referralId,
    eventType: "referral_dispatched_patient",
    title: "Referral Sent to Hospital",
    message: `Your referral (${referralId}) has been sent to ${hospitalName}. Awaiting hospital confirmation.`,
    requestedExternalChannels: ["sms", "whatsapp"],
    isDemoData: updated.isDemoData,
  });

  // Sync to Firestore in background
  if (db && typeof window !== "undefined" && window.navigator?.onLine !== false) {
    withTimeout(
      updateDoc(doc(db, FIRESTORE_COLLECTION, referralId), {
        status: updated.status,
        targetHospitalId: updated.targetHospitalId,
        targetHospitalName: updated.targetHospitalName,
        dispatchedAt: updated.dispatchedAt,
        timeline: updated.timeline,
        notifications: updated.notifications,
      }),
      2500
    ).catch((e) => console.warn("Firestore dispatch sync skipped:", e.message));
  }

  // Increment active referral count on hospital record
  try {
    const allHosps = await getHospitals();
    const targetHosp = allHosps.find((h) => h.id === hospitalId);
    if (targetHosp) {
      await updateHospitalCapacity(
        hospitalId,
        {
          activeReferrals: (targetHosp.activeReferrals || 0) + 1,
          historyNote: `Referral ${referralId} received in triage queue`,
        },
        { name: "Referral Dispatch System", email: "system@relieflaser.med" }
      );
    }
  } catch (err) {
    console.warn("Hospital referral counter sync skipped:", err.message);
  }

  return updated;
}

