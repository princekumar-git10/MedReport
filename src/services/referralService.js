/**
 * Intelligent Alternative Hospital Matching Service
 *
 * When a hospital rejects a referral or cannot accept a patient:
 * 1. Sweeps any expired capacity holds across the network so freed beds are visible
 * 2. Excludes all previously declined hospitals
 * 3. Re-runs matching engine against remaining accredited network hospitals
 * 4. Returns ranked eligible alternatives with explanations and notifies doctor if needed
 */
export async function getAlternativeHospitalsForReferral(referralId, options = {}) {
  await sweepExpiredCapacityHolds();

  const referral = await getReferralById(referralId);
  if (!referral) {
    throw new Error(`Referral ${referralId} not found in database.`);
  }

  // 1. Gather all excluded hospitals
  const previouslyRejected = Array.isArray(referral.rejectedHospitalIds) ? referral.rejectedHospitalIds : [];
  const additionalExcluded = Array.isArray(options.excludeHospitalIds) ? options.excludeHospitalIds : [];
  const currentTarget = referral.targetHospitalId ? [referral.targetHospitalId] : [];

  const allExcludedIds = Array.from(new Set([
    ...previouslyRejected,
    ...additionalExcluded,
    ...currentTarget
  ]));

  // 2. Retrieve all hospitals and filter out excluded
  const allHospitals = await getHospitals();
  const candidateHospitals = allHospitals.filter(h => !allExcludedIds.includes(h.id));

  // 3. Re-run matching engine with hard clinical filters and weighted ranking
  const engineResult = runMatchingEngine(referral, candidateHospitals, { weights: options.weights });

  // Notify patient cleanly if alternatives are being proposed
  if (engineResult.eligibleHospitals.length > 0 && referral.status === "Rejected") {
    await dispatchNotification({
      recipientRole: "doctor",
      recipientId: referral.doctorId,
      referralId,
      eventType: "alternative_hospitals_found",
      title: `${engineResult.eligibleHospitals.length} Alternative Hospital(s) Verified`,
      message: `Top alternative for ${referral.patient?.name}: ${engineResult.eligibleHospitals[0].hospital.name} (${engineResult.eligibleHospitals[0].matchScore}% match). Physician authorization required to redirect.`,
      requestedExternalChannels: [],
      isDemoData: referral.isDemoData,
    });
  }

  return {
    referral,
    evaluatedAt: new Date().toISOString(),
    excludedHospitalIds: allExcludedIds,
    previousRejections: referral.rejectionHistory || [],
    alternatives: engineResult.eligibleHospitals,
    unsuitableAlternatives: engineResult.unsuitableHospitals,
    totalEvaluated: candidateHospitals.length,
    emergencyEscalationNeeded: engineResult.emergencyEscalationNeeded,
  };
}

/**
 * Doctor Authorizes Referral Redirection to an Alternative Hospital
 */
export async function redirectReferralToHospital({
  referralId,
  newHospitalId,
  newHospitalName,
  doctorName = "Referring Clinician",
  doctorEmail = "",
  redirectionNotes = "",
}) {
  const list = getLocalReferrals();
  const index = list.findIndex(r => r.id === referralId);
  if (index === -1) {
    throw new Error(`Referral ${referralId} not found`);
  }

  const current = list[index];
  validateStatusTransition(current.status, "Pending");

  // Prevent routing to an already declined hospital
  if (Array.isArray(current.rejectedHospitalIds) && current.rejectedHospitalIds.includes(newHospitalId)) {
    throw new Error(`Redirect blocked: Hospital ${newHospitalId} previously declined this referral.`);
  }

  const nowIso = new Date().toISOString();

  // Verify target hospital
  const allHospitals = await getHospitals();
  const targetHospital = allHospitals.find(h => h.id === newHospitalId);
  if (!targetHospital) {
    throw new Error(`Target hospital ${newHospitalId} not found`);
  }

  // Safely release any active capacity hold from prior hospital
  if (current.targetHospitalId && current.capacityHold?.held && current.capacityHold?.status === "Active") {
    await releaseHospitalCapacityHold(current.targetHospitalId, {
      referralId,
      reason: "Redirected to alternative hospital",
      actorName: doctorName,
      actorEmail: doctorEmail || current.doctorId,
    });
  }

  // Preserve previous hospital in rejected list if not already recorded
  const prevHospId = current.targetHospitalId;
  const prevHospName = current.targetHospitalName || "Previous Hospital";
  const rejectedList = Array.isArray(current.rejectedHospitalIds) ? current.rejectedHospitalIds : [];
  const updatedRejectedIds = prevHospId && !rejectedList.includes(prevHospId)
    ? [...rejectedList, prevHospId]
    : rejectedList;

  const pastRejectionHistory = Array.isArray(current.rejectionHistory) ? current.rejectionHistory : [];
  let updatedRejectionHistory = [...pastRejectionHistory];
  if (prevHospId && current.rejectionReason && !pastRejectionHistory.some(h => h.hospitalId === prevHospId)) {
    updatedRejectionHistory.push({
      hospitalId: prevHospId,
      hospitalName: prevHospName,
      reason: current.rejectionReason,
      clinicalNotes: current.clinicalNotes || "",
      rejectedAt: current.rejectedAt || nowIso,
      rejectedBy: current.rejectedBy || "Hospital Staff",
    });
  }

  const resolvedHospName = newHospitalName || targetHospital.name;

  const updatedReferral = {
    ...current,
    status: "Pending", // Transition to pending for the new hospital
    targetHospitalId: newHospitalId,
    targetHospitalName: resolvedHospName,
    redirectedAt: nowIso,
    redirectedBy: doctorName,
    capacityHold: null,
    rejectedHospitalIds: updatedRejectedIds,
    rejectionHistory: updatedRejectionHistory,
    timeline: [
      ...current.timeline,
      {
        status: "Pending",
        timestamp: nowIso,
        note: `Referral authorized and redirected to ${resolvedHospName} by ${doctorName}.${redirectionNotes ? ` Reason: ${redirectionNotes}` : ""}`,
        by: doctorName,
      }
    ],
    notifications: [
      ...(current.notifications || []),
      {
        notifiedAt: nowIso,
        target: "patient_and_hospital",
        title: "Alternative Hospital Proposed & Sent",
        message: `Your referral (${referralId}) has been authorized and sent to ${resolvedHospName} admissions desk.`
      }
    ]
  };

  list[index] = updatedReferral;
  saveLocalReferrals(list);

  // Dispatch live in-app notifications to Hospital B and Patient
  await dispatchNotification({
    recipientRole: "hospital",
    recipientId: newHospitalId,
    referralId,
    eventType: "referral_redirected",
    title: "Redirected Priority Referral Received",
    message: `${doctorName} redirected ${updatedReferral.priority} referral ${referralId} (${updatedReferral.clinicalRequirements?.procedure}) to ${resolvedHospName}.`,
    requestedExternalChannels: ["email"],
    isDemoData: updatedReferral.isDemoData,
  });
  await dispatchNotification({
    recipientRole: "patient",
    recipientId: updatedReferral.patient?.patientId || referralId,
    referralId,
    eventType: "referral_redirected_patient",
    title: "Referral Redirected to New Hospital",
    message: `Your referral (${referralId}) has been sent to ${resolvedHospName}. You will be notified once they confirm.`,
    requestedExternalChannels: ["sms", "whatsapp"],
    isDemoData: updatedReferral.isDemoData,
  });

  // Increment active referrals counter on new hospital
  try {
    await updateHospitalCapacity(
      newHospitalId,
      {
        activeReferrals: (targetHospital.activeReferrals || 0) + 1,
        historyNote: `Redirected referral ${referralId} assigned`,
      },
      { name: "Alternative Matching Engine", email: "system@relieflaser.med" }
    );
  } catch (err) {
    console.warn("Capacity update skipped:", err.message);
  }

  // Call backend API in background
  try {
    if (typeof window !== "undefined") {
      fetch("/api/redirect-referral", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          referralId,
          newHospitalId,
          newHospitalName: resolvedHospName,
          doctorName,
          doctorEmail,
          redirectionNotes,
        })
      }).catch(e => console.warn("Backend API redirect sync (non-blocking):", e.message));
    }
  } catch (apiErr) {
    console.warn("API redirect call error:", apiErr.message);
  }

  // Firestore sync in background
  if (db && typeof window !== "undefined" && window.navigator?.onLine !== false) {
    withTimeout(
      updateDoc(doc(db, FIRESTORE_COLLECTION, referralId), {
        status: "Pending",
        targetHospitalId: newHospitalId,
        targetHospitalName: resolvedHospName,
        redirectedAt: nowIso,
        redirectedBy: doctorName,
        capacityHold: null,
        rejectedHospitalIds: updatedRejectedIds,
        rejectionHistory: updatedRejectionHistory,
        timeline: updatedReferral.timeline,
        notifications: updatedReferral.notifications
      }),
      2500
    ).catch(e => console.warn("Firestore redirect sync skipped:", e.message));
  }

  return updatedReferral;
}

/**
 * Safely release or expire a capacity hold on a referral, restoring hospital availability telemetry.
 */
export async function releaseOrExpireCapacityHold(referralId, reason = "Cancelled", actor = {}) {
  const list = getLocalReferrals();
  const index = list.findIndex((r) => r.id === referralId);
  if (index === -1) throw new Error(`Referral ${referralId} not found.`);

  const referral = list[index];
  if (!referral.capacityHold?.held || referral.capacityHold?.status !== "Active") {
    return referral; // Nothing active to release
  }

  const nowIso = new Date().toISOString();
  const actorName = actor.name || "System Capacity Guard";
  const actorEmail = actor.email || "system@relieflaser.med";

  // Release bed reservation on target hospital
  if (referral.targetHospitalId) {
    await releaseHospitalCapacityHold(referral.targetHospitalId, {
      referralId,
      reason,
      actorName,
      actorEmail,
      icuReservedFallback: Boolean(referral.clinicalRequirements?.icuRequired),
      emergencyReservedFallback: Boolean(referral.clinicalRequirements?.emergencySupportRequired),
    });
  }

  const holdState = reason === "Expired" ? "Expired" : "Released";
  const updated = {
    ...referral,
    capacityHold: {
      ...referral.capacityHold,
      held: false,
      status: holdState,
      releasedAt: nowIso,
      releaseReason: reason,
      releasedBy: actorEmail,
      note: `Capacity hold ${holdState.toLowerCase()} (${reason}) at ${new Date(nowIso).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}`,
    },
    timeline: [
      ...referral.timeline,
      {
        status: referral.status,
        timestamp: nowIso,
        note: `Capacity bed hold ${holdState.toLowerCase()} safely (${reason}). Bed returned to hospital availability pool.`,
        by: actorName,
      },
    ],
  };

  list[index] = updated;
  saveLocalReferrals(list);

  await dispatchNotification({
    recipientRole: "hospital",
    recipientId: referral.targetHospitalId,
    referralId,
    eventType: "capacity_hold_released",
    title: `Bed Hold ${holdState}`,
    message: `Capacity hold for referral ${referralId} was safely ${holdState.toLowerCase()} (${reason}). Bed returned to open capacity.`,
    requestedExternalChannels: [],
    isDemoData: referral.isDemoData,
  });

  if (db && typeof window !== "undefined" && window.navigator?.onLine !== false) {
    withTimeout(
      updateDoc(doc(db, FIRESTORE_COLLECTION, referralId), {
        capacityHold: updated.capacityHold,
        timeline: updated.timeline,
      }),
      2500
    ).catch(() => {});
  }

  return updated;
}

/**
 * Sweep expired capacity holds automatically and restore open capacity safely.
 */
export async function sweepExpiredCapacityHolds() {
  const list = getLocalReferrals();
  const now = Date.now();
  const released = [];

  for (const r of list) {
    if (
      r.capacityHold?.held &&
      r.capacityHold?.status === "Active" &&
      r.capacityHold?.expiresAt &&
      new Date(r.capacityHold.expiresAt).getTime() <= now
    ) {
      try {
        const updated = await releaseOrExpireCapacityHold(r.id, "Expired", {
          name: "Auto Hold Expiry Guard",
          email: "system@relieflaser.med",
        });
        released.push(updated.id);
      } catch (e) {
        console.warn("Expired hold sweep failed for", r.id, e.message);
      }
    }
  }
  return released;
}

/**
 * Advance post-acceptance patient journey milestones cleanly:
 * Accepted -> Transfer Initiated -> Patient Arrived -> Completed
 */
export async function updateReferralJourneyStep(referralId, nextStep, actor = {}) {
  const allowedSteps = ["Transfer Initiated", "Patient Arrived", "Completed"];
  if (!allowedSteps.includes(nextStep)) {
    throw new Error(`Invalid journey milestone "${nextStep}".`);
  }

  const list = getLocalReferrals();
  const index = list.findIndex((r) => r.id === referralId);
  if (index === -1) throw new Error(`Referral ${referralId} not found.`);

  const current = list[index];
  validateStatusTransition(current.status, nextStep);

  const nowIso = new Date().toISOString();
  const actorName = actor.name || "Care Coordinator";

  // If Completed, mark capacity hold as converted to admission
  let nextHold = current.capacityHold;
  if (nextStep === "Completed" && current.capacityHold?.held) {
    nextHold = {
      ...current.capacityHold,
      status: "ConvertedToAdmission",
      convertedAt: nowIso,
      note: "Bed converted from temporary hold to confirmed admission",
    };
  }

  const milestoneNotes = {
    "Transfer Initiated": `Patient transfer initiated toward ${current.targetHospitalName}.`,
    "Patient Arrived": `Patient arrived at ${current.targetHospitalName} admissions desk.`,
    Completed: `Admission confirmed & treatment check-in completed at ${current.targetHospitalName}.`,
  };

  const updated = {
    ...current,
    status: nextStep,
    capacityHold: nextHold,
    timeline: [
      ...current.timeline,
      {
        status: nextStep,
        timestamp: nowIso,
        note: actor.note || milestoneNotes[nextStep],
        by: actorName,
      },
    ],
    notifications: [
      ...(current.notifications || []),
      {
        notifiedAt: nowIso,
        target: "doctor_and_patient",
        title: `Referral Status: ${nextStep}`,
        message: milestoneNotes[nextStep],
      },
    ],
  };

  list[index] = updated;
  saveLocalReferrals(list);

  await dispatchNotification({
    recipientRole: "patient",
    recipientId: updated.patient?.patientId || referralId,
    referralId,
    eventType: "referral_status_changed",
    title: `Status Update: ${nextStep}`,
    message: milestoneNotes[nextStep],
    requestedExternalChannels: ["sms", "whatsapp"],
    isDemoData: updated.isDemoData,
  });
  await dispatchNotification({
    recipientRole: "doctor",
    recipientId: updated.doctorId,
    referralId,
    eventType: "referral_status_changed",
    title: `${updated.patient?.name}: ${nextStep}`,
    message: `${milestoneNotes[nextStep]} (Referral ${referralId})`,
    requestedExternalChannels: [],
    isDemoData: updated.isDemoData,
  });

  if (db && typeof window !== "undefined" && window.navigator?.onLine !== false) {
    withTimeout(
      updateDoc(doc(db, FIRESTORE_COLLECTION, referralId), {
        status: nextStep,
        capacityHold: nextHold || null,
        timeline: updated.timeline,
        notifications: updated.notifications,
      }),
      2500
    ).catch(() => {});
  }

  return updated;
}

