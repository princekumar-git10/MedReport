// Explicit referral status transition state machine
export const VALID_STATUS_TRANSITIONS = {
  Created: ["Pending", "Cancelled"],
  Pending: ["Accepted", "Rejected", "Information Requested", "Escalated", "Cancelled"],
  "Information Requested": ["Pending", "Accepted", "Rejected", "Cancelled"],
  Rejected: ["Pending", "Escalated", "Cancelled"],
  Escalated: ["Pending", "Accepted", "Cancelled"],
  Accepted: ["Transfer Initiated", "Patient Arrived", "Completed", "Cancelled"],
  "Transfer Initiated": ["Patient Arrived", "Completed", "Cancelled"],
  "Patient Arrived": ["Completed"],
  Completed: [],
  Cancelled: [],
};

export function validateStatusTransition(currentStatus, nextStatus) {
  const from = currentStatus || "Created";
  const allowed = VALID_STATUS_TRANSITIONS[from];
  if (!allowed) {
    throw new Error(`Unknown referral state "${from}".`);
  }
  if (!allowed.includes(nextStatus)) {
    throw new Error(`Invalid status transition from "${from}" to "${nextStatus}". Allowed next states: ${allowed.join(", ") || "None (terminal state)"}.`);
  }
  return true;
}

// Helper for non-blocking Firestore sync
function withTimeout(promise, ms = 2000) {
  let timer;
  const timeout = new Promise((_, reject) => {
    timer = setTimeout(() => reject(new Error("Cloud sync timed out")), ms);
  });
  return Promise.race([
    promise.finally(() => clearTimeout(timer)),
    timeout
  ]);
}

