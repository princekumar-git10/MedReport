/**
 * Subscribe to real-time referral changes across same-tab, cross-tab storage, and Firestore.
 */
export function subscribeToReferrals(callback) {
  const emit = () => callback(getLocalReferrals());

  const onCustom = (e) => {
    if (Array.isArray(e.detail)) callback(e.detail);
    else emit();
  };
  const onStorage = (e) => {
    if (e.key === STORAGE_KEY) emit();
  };

  if (typeof window !== "undefined") {
    window.addEventListener("relief_referrals_updated", onCustom);
    window.addEventListener("storage", onStorage);
  }

  let unsubFirestore = null;
  if (db && typeof window !== "undefined" && window.navigator?.onLine !== false) {
    try {
      unsubFirestore = onSnapshot(
        collection(db, FIRESTORE_COLLECTION),
        (snap) => {
          if (!snap.empty) {
            const cloudList = [];
            snap.forEach((d) => cloudList.push({ id: d.id, ...d.data() }));
            saveLocalReferrals(cloudList);
            callback(cloudList);
          }
        },
        () => {}
      );
    } catch {
      // Ignore if Firestore offline
    }
  }

  return () => {
    if (typeof window !== "undefined") {
      window.removeEventListener("relief_referrals_updated", onCustom);
      window.removeEventListener("storage", onStorage);
    }
    if (typeof unsubFirestore === "function") unsubFirestore();
  };
}


