// Standardized rejection reasons
export const VALID_REJECTION_REASONS = [
  "No available bed.",
  "ICU unavailable.",
  "Required treatment unavailable.",
  "Specialist unavailable.",
  "Equipment unavailable.",
  "Hospital unable to handle the case.",
  "Other."
];

/**
 * Execute Hospital Referral Action (Accept, Reject, Request Information).
 * Enforces:
 * - Capacity recheck
 * - Mandatory facilities verification
 * - Authorized confirmation
 * - Explicit capacity hold authorization
 * - Idempotency & duplicate prevention
 * - Full audit timeline & notification
 */
export async function executeHospitalReferralAction({
  action, // "accept" | "reject" | "request_info"
  referralId,
  hospitalId,
  staffName = "Hospital Staff",
  staffEmail = "staff@hospital.med",
  authorizeCapacityHold = false,
  rejectionReason = "",
  clinicalNotes = "",
  requestedInfo = "",
  message = ""
}) {
  const list = getLocalReferrals();
  const index = list.findIndex((r) => r.id === referralId);
  if (index === -1) {
    throw new Error(`Referral ${referralId} not found in database.`);
  }

  const referral = list[index];

  // 1. Validate state transition & prevent conflicting duplicate actions
  const nextStatusMap = {
    accept: "Accepted",
    reject: "Rejected",
    request_info: "Information Requested",
  };
  const nextTargetStatus = nextStatusMap[action];
  if (!nextTargetStatus) {
    throw new Error(`Unsupported referral action: "${action}"`);
  }
  validateStatusTransition(referral.status, nextTargetStatus);

  // 2. Fetch target hospital and recheck capacity
  const allHospitals = await getHospitals();
  const hospIndex = allHospitals.findIndex((h) => h.id === hospitalId);
  if (hospIndex === -1) {
    throw new Error(`Hospital ${hospitalId} not found.`);
  }
  const hospital = allHospitals[hospIndex];

  // Check authorization
  const cleanStaffEmail = (staffEmail || "staff@hospital.med").trim().toLowerCase();
  const isStaffAuthorized = 
    !hospital.authorizedStaff || 
    hospital.authorizedStaff.length === 0 || 
    hospital.authorizedStaff.some((s) => s.toLowerCase() === cleanStaffEmail) ||
    hospital.isDemoData;

  if (!isStaffAuthorized) {
    throw new Error(`Unauthorized: ${cleanStaffEmail} is not registered as authorized personnel for ${hospital.name}.`);
  }

  const nowIso = new Date().toISOString();
  let updatedReferral = { ...referral };

  // 3. ACTION: ACCEPT
  if (action === "accept") {
    // Recheck hospital capacity
    if (hospital.availableBeds <= 0) {
      throw new Error(`Cannot accept referral: ${hospital.name} currently has 0 available general beds.`);
    }

    // Verify ICU if required
    if (referral.clinicalRequirements?.icuRequired) {
      const openIcu = hospital.icuFacilities?.availableBeds ?? hospital.icuBedCapacity ?? 0;
      if (openIcu <= 0 || !hospital.icuFacilities?.available) {
        throw new Error(`Cannot accept referral: Case requires critical care ICU, but ${hospital.name} reports 0 open ICU beds.`);
      }
    }

    // Verify Emergency bay if required
    if (referral.clinicalRequirements?.emergencySupportRequired) {
      const openEmerg = hospital.availableEmergencyBeds ?? hospital.emergencyFacilities?.availableBeds ?? 0;
      if (openEmerg <= 0 || !hospital.emergencyFacilities?.available) {
        throw new Error(`Cannot accept referral: Emergency trauma bay is at full capacity.`);
      }
    }

    // Atomic Capacity Hold Reservation (only if explicitly authorized)
    let holdDetails = {
      held: false,
      status: "None",
      heldAt: nowIso,
      heldBy: cleanStaffEmail,
      note: "No capacity hold requested",
    };

    if (authorizeCapacityHold) {
      const { hold } = await reserveHospitalCapacityHold(hospitalId, {
        referralId,
        icuRequired: Boolean(referral.clinicalRequirements?.icuRequired),
        emergencyRequired: Boolean(referral.clinicalRequirements?.emergencySupportRequired),
        staffName,
        staffEmail: cleanStaffEmail,
        durationMinutes: 120,
      });
      holdDetails = {
        held: true,
        holdId: hold.holdId,
        status: "Active",
        heldAt: hold.heldAt,
        expiresAt: hold.expiresAt,
        heldBy: cleanStaffEmail,
        icuReserved: hold.icuReserved,
        emergencyBayReserved: hold.emergencyBayReserved,
        note: `Bed hold (${hold.holdId}) reserved until ${new Date(hold.expiresAt).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}`,
      };
    }

    // Update referral statistics counters on hospital
    try {
      const refreshedHosps = await getHospitals();
      const latestHosp = refreshedHosps.find((h) => h.id === hospitalId) || hospital;
      await updateHospitalCapacity(
        hospitalId,
        {
          acceptedReferrals: (latestHosp.acceptedReferrals || 0) + 1,
          activeReferrals: Math.max(0, (latestHosp.activeReferrals || 1) - 1),
          historyNote: `Referral ${referralId} accepted by ${staffName}${authorizeCapacityHold ? " (with bed hold)" : ""}`,
        },
        { name: staffName, email: cleanStaffEmail }
      );
    } catch (err) {
      console.warn("Accepted referral counter update skipped:", err.message);
    }

    updatedReferral = {
      ...referral,
      status: "Accepted",
      acceptedBy: staffName,
      acceptedByEmail: cleanStaffEmail,
      acceptedAt: nowIso,
      targetHospitalId: hospitalId,
      targetHospitalName: hospital.name,
      capacityHold: holdDetails,
      admissionNotice: "Admission prioritized based on authorized hospital capacity verification. Final clinical triaging upon patient arrival.",
      timeline: [
        ...referral.timeline,
        {
          status: "Accepted",
          timestamp: nowIso,
          note: clinicalNotes 
            ? `Referral accepted by ${staffName} (${cleanStaffEmail}). Clinical note: ${clinicalNotes}` 
            : `Referral explicitly accepted by ${staffName}. Bed admission priority confirmed.`,
          by: staffName,
          staffEmail: cleanStaffEmail,
          capacityHoldAuthorized: Boolean(authorizeCapacityHold)
        }
      ],
      notifications: [
        ...(referral.notifications || []),
        {
          notifiedAt: nowIso,
          target: "doctor_and_patient",
          title: "Referral Accepted",
          message: `Referral ${referralId} was accepted by ${hospital.name}. Priority admission confirmation issued.`
        }
      ]
    };

    // Real-time role notifications (Doctor + Patient sanitized)
    await dispatchNotification({
      recipientRole: "doctor",
      recipientId: referral.doctorId,
      referralId,
      eventType: "referral_accepted",
      title: `Accepted by ${hospital.name}`,
      message: `${hospital.name} (${staffName}) accepted referral ${referralId} for ${referral.patient?.name}.${authorizeCapacityHold ? ` Capacity hold active until ${new Date(holdDetails.expiresAt).toLocaleTimeString()}.` : ""}`,
      requestedExternalChannels: ["email"],
      isDemoData: referral.isDemoData,
    });
    await dispatchNotification({
      recipientRole: "patient",
      recipientId: referral.patient?.patientId || referralId,
      referralId,
      eventType: "referral_accepted_patient",
      title: "Hospital Confirmed Your Referral",
      message: `${hospital.name} has confirmed admission readiness for your referral ${referralId}. Open Patient Dashboard for directions & arrival instructions.`,
      requestedExternalChannels: ["sms", "email", "whatsapp"],
      isDemoData: referral.isDemoData,
    });
  } 

  // 4. ACTION: REJECT
  else if (action === "reject") {
    const cleanReason = (rejectionReason || "").trim();
    if (!cleanReason || !VALID_REJECTION_REASONS.includes(cleanReason)) {
      throw new Error(`Valid rejection reason is required. Must be one of: ${VALID_REJECTION_REASONS.join(", ")}`);
    }

    // Release any pre-existing active capacity hold cleanly
    if (referral.capacityHold?.held && referral.capacityHold?.status === "Active") {
      await releaseHospitalCapacityHold(hospitalId, {
        referralId,
        reason: "Cancelled due to rejection",
        actorName: staffName,
        actorEmail: cleanStaffEmail,
      });
    }

    try {
      await updateHospitalCapacity(
        hospitalId,
        {
          rejectedReferrals: (hospital.rejectedReferrals || 0) + 1,
          activeReferrals: Math.max(0, (hospital.activeReferrals || 1) - 1),
          historyNote: `Referral ${referralId} declined (${cleanReason})`,
        },
        { name: staffName, email: cleanStaffEmail }
      );
    } catch (err) {
      console.warn("Rejected referral counter update skipped:", err.message);
    }

    const pastRejections = Array.isArray(referral.rejectionHistory) ? referral.rejectionHistory : [];
    const pastRejectedIds = Array.isArray(referral.rejectedHospitalIds) ? referral.rejectedHospitalIds : [];

    updatedReferral = {
      ...referral,
      status: "Rejected",
      rejectedBy: staffName,
      rejectedByEmail: cleanStaffEmail,
      rejectedAt: nowIso,
      rejectionReason: cleanReason,
      clinicalNotes: clinicalNotes.trim(),
      capacityHold: referral.capacityHold?.held
        ? { ...referral.capacityHold, held: false, status: "Released", releasedAt: nowIso, releaseReason: cleanReason }
        : referral.capacityHold,
      rejectedHospitalIds: Array.from(new Set([...pastRejectedIds, hospitalId])),
      rejectionHistory: [
        ...pastRejections,
        {
          hospitalId,
          hospitalName: hospital.name,
          reason: cleanReason,
          clinicalNotes: clinicalNotes.trim(),
          rejectedAt: nowIso,
          rejectedBy: staffName,
          rejectedByEmail: cleanStaffEmail,
        }
      ],
      lastRejectedHospital: {
        id: hospitalId,
        name: hospital.name,
        reason: cleanReason,
        rejectedAt: nowIso,
      },
      timeline: [
        ...referral.timeline,
        {
          status: "Rejected",
          timestamp: nowIso,
          note: `Referral declined by ${staffName} (${cleanStaffEmail}). Reason: ${cleanReason}${clinicalNotes ? `. Clinical note: ${clinicalNotes}` : ""}`,
          by: staffName,
          staffEmail: cleanStaffEmail,
          reason: cleanReason
        }
      ],
      notifications: [
        ...(referral.notifications || []),
        {
          notifiedAt: nowIso,
          target: "doctor_and_patient",
          title: "Hospital Declined — Finding Alternatives",
          message: `Referral ${referralId} could not be accommodated by ${hospital.name}. Your physician is identifying alternative verified hospitals.`
        }
      ]
    };

    await dispatchNotification({
      recipientRole: "doctor",
      recipientId: referral.doctorId,
      referralId,
      eventType: "referral_rejected",
      title: `Referral Declined by ${hospital.name}`,
      message: `${hospital.name} declined referral ${referralId} (${referral.patient?.name}). Reason: ${cleanReason}. Launch Alternative Hospital Matching to redirect without re-entry.`,
      requestedExternalChannels: ["sms", "email"],
      isDemoData: referral.isDemoData,
    });
    await dispatchNotification({
      recipientRole: "patient",
      recipientId: referral.patient?.patientId || referralId,
      referralId,
      eventType: "referral_rejected_patient",
      title: "Matching Alternative Hospital",
      message: `${hospital.name} could not accommodate referral ${referralId}. Your doctor is assigning an alternative accredited center.`,
      requestedExternalChannels: ["sms", "whatsapp"],
      isDemoData: referral.isDemoData,
    });
  }

  // 5. ACTION: REQUEST MORE INFORMATION
  else if (action === "request_info") {
    const infoText = (requestedInfo || message || "").trim();
    if (!infoText) {
      throw new Error("Please describe the additional information, laboratory tests, or clinical documents requested.");
    }

    const newRequest = {
      id: `inforeq-${Date.now()}`,
      requestedBy: staffName,
      requestedByEmail: cleanStaffEmail,
      requestedInfo: infoText,
      message: (message || infoText).trim(),
      requestedAt: nowIso,
      status: "Pending"
    };

    updatedReferral = {
      ...referral,
      status: "Information Requested",
      infoRequests: [...(referral.infoRequests || []), newRequest],
      timeline: [
        ...referral.timeline,
        {
          status: "Information Requested",
          timestamp: nowIso,
          note: `Additional documentation requested by ${staffName}: "${infoText}"`,
          by: staffName,
          staffEmail: cleanStaffEmail
        }
      ],
      notifications: [
        ...(referral.notifications || []),
        {
          notifiedAt: nowIso,
          target: "doctor_and_patient",
          title: "Additional Information Requested",
          message: `${hospital.name} requested clarifying documents for referral ${referralId}.`
        }
      ]
    };

    await dispatchNotification({
      recipientRole: "doctor",
      recipientId: referral.doctorId,
      referralId,
      eventType: "referral_info_requested",
      title: `Info Requested by ${hospital.name}`,
      message: `${hospital.name} (${staffName}) requested clarification for referral ${referralId}: "${infoText}".`,
      requestedExternalChannels: ["email"],
      isDemoData: referral.isDemoData,
    });
  }

  // 6. Persist locally and sync
  list[index] = updatedReferral;
  saveLocalReferrals(list);

  // 7. Call Backend API endpoint
  try {
    if (typeof window !== "undefined") {
      fetch("/api/referral-action", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          action,
          referralId,
          hospitalId,
          staffName,
          staffEmail: cleanStaffEmail,
          authorizeCapacityHold,
          rejectionReason,
          clinicalNotes,
          requestedInfo,
          message
        })
      }).catch((e) => console.warn("Backend API sync (non-blocking):", e.message));
    }
  } catch (apiErr) {
    console.warn("Backend API call non-blocking error:", apiErr.message);
  }

  // 8. Firestore sync in background
  if (db && typeof window !== "undefined" && window.navigator?.onLine !== false) {
    withTimeout(
      updateDoc(doc(db, FIRESTORE_COLLECTION, referralId), {
        status: updatedReferral.status,
        acceptedBy: updatedReferral.acceptedBy || null,
        acceptedAt: updatedReferral.acceptedAt || null,
        rejectedBy: updatedReferral.rejectedBy || null,
        rejectedAt: updatedReferral.rejectedAt || null,
        rejectionReason: updatedReferral.rejectionReason || null,
        capacityHold: updatedReferral.capacityHold || null,
        infoRequests: updatedReferral.infoRequests || [],
        timeline: updatedReferral.timeline,
        notifications: updatedReferral.notifications || []
      }),
      2500
    ).catch((e) => console.warn("Firestore referral action sync skipped:", e.message));
  }

  const refreshedList = await getHospitals().catch(() => []);
  const latestHospital = refreshedList.find((h) => h.id === hospitalId) || hospital;

  return {
    success: true,
    action,
    referral: updatedReferral,
    hospital: latestHospital
  };
}

